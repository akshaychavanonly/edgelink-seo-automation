function escapeHTML(value) {
  return String(value ?? "").replace(
    /[&<>"']/g,
    (char) =>
      ({
        "&": "&amp;",
        "<": "&lt;",
        ">": "&gt;",
        '"': "&quot;",
        "'": "&#39;",
      })[char],
  );
}

async function generateAuditPDF(audit) {
  if (!audit.result) {
    throw new Error("Completed audit result not found");
  }

  const result = audit.result;
  const client = audit.client;
  const scores = result.scoreBreakdown || {};

  const scoreRows = [
    ["Technical SEO", scores.technical],
    ["On-page SEO", scores.on_page],
    ["Content", scores.content],
    ["Core Web Vitals", scores.core_web_vitals],
    ["Schema", scores.schema],
  ];

  const listItems = (items) =>
    (Array.isArray(items) ? items : [])
      .map(
        (item) =>
          `<li>${escapeHTML(
            typeof item === "string" ? item : item.finding,
          )}</li>`,
      )
      .join("");

  const recommendations = Array.isArray(result.recommendations)
    ? result.recommendations
    : [];

  const html = `
  <!DOCTYPE html>
  <html lang="en">
  <head>
    <meta charset="UTF-8" />
    <style>
      @page { size: A4; margin: 18mm; }
      * { box-sizing: border-box; }
      body {
        font-family: Arial, sans-serif;
        color: #172033;
        font-size: 12px;
        line-height: 1.6;
      }
      .header {
        background: #0d9488;
        color: white;
        padding: 28px;
        border-radius: 8px;
      }
      .header h1 { margin: 0; font-size: 25px; }
      .header p { margin: 6px 0 0; }
      h2 {
        font-size: 17px;
        margin-top: 28px;
        color: #0f766e;
        border-bottom: 1px solid #cbd5e1;
        padding-bottom: 6px;
      }
      .score {
        font-size: 43px;
        font-weight: bold;
        color: #0f766e;
        margin: 10px 0;
      }
      table {
        width: 100%;
        border-collapse: collapse;
        margin-top: 12px;
      }
      th, td {
        text-align: left;
        padding: 10px;
        border-bottom: 1px solid #e2e8f0;
      }
      th { background: #f0fdfa; }
      .recommendation {
        border: 1px solid #e2e8f0;
        border-left: 4px solid #0d9488;
        border-radius: 4px;
        padding: 14px;
        margin: 12px 0;
        break-inside: avoid;
        overflow-wrap: anywhere;
      }
      .priority {
        font-weight: bold;
        color: #b45309;
      }
      .footer {
        margin-top: 32px;
        font-size: 10px;
        color: #64748b;
      }
      li { margin: 5px 0; }
    </style>
  </head>
  <body>
    <div class="header">
      <h1>EDGELINK TECHNOLOGY</h1>
      <p>SEO Automation Audit Report</p>
    </div>

    <h2>Client Information</h2>
    <p><strong>Client:</strong> ${escapeHTML(client.name)}</p>
    <p><strong>Website:</strong> ${escapeHTML(audit.websiteUrl)}</p>
    <p><strong>Audit Date:</strong> ${escapeHTML(
      new Date(audit.createdAt).toLocaleDateString("en-IN"),
    )}</p>

    <h2>Overall SEO Score</h2>
    <div class="score">${escapeHTML(result.overallScore)}/100</div>

    <h2>Executive Summary</h2>
    <p>${escapeHTML(result.executiveSummary)}</p>

    <h2>SEO Score Breakdown</h2>
    <table>
      <thead>
        <tr><th>Category</th><th>Score</th></tr>
      </thead>
      <tbody>
        ${scoreRows
          .map(
            ([name, score]) => `
          <tr>
            <td>${escapeHTML(name)}</td>
            <td>${escapeHTML(score)}/100</td>
          </tr>
        `,
          )
          .join("")}
      </tbody>
    </table>

    <h2>Critical Issues</h2>
    <ul>${listItems(result.criticalIssues)}</ul>

    <h2>Important Issues</h2>
    <ul>${listItems(result.importantIssues)}</ul>

    <h2>Quick Wins</h2>
    <ul>${listItems(result.quickWins)}</ul>

    <h2>AI Recommendations</h2>
    ${recommendations
      .map(
        (rec) => `
      <div class="recommendation">
        <p class="priority">
          ${escapeHTML(rec.priority)} -
          ${escapeHTML(rec.category)}
        </p>
        <p><strong>Finding:</strong> ${escapeHTML(rec.finding)}</p>
        <p><strong>Fix:</strong> ${escapeHTML(rec.fix)}</p>
        <p><strong>Impact:</strong> ${escapeHTML(rec.estimated_impact)}</p>
        <p><strong>Effort:</strong> ${escapeHTML(rec.effort)}</p>
        <p><strong>Verification:</strong>
          ${escapeHTML(rec.falsifiability_check)}
        </p>
      </div>
    `,
      )
      .join("")}

    <div class="footer">
      Generated by Edgelink SEO Automation Dashboard.
      ${
        process.env.USE_MOCK_AI !== "false" || process.env.USE_MOCKS === "true"
          ? "Demo report: AI and/or external SEO metrics are mocked."
          : ""
      }
    </div>
  </body>
  </html>`;

  let browser;

  if (process.env.VERCEL === "1") {
    const { default: puppeteer } = await import("puppeteer-core");
    const { default: chromium } = await import("@sparticuz/chromium");

    browser = await puppeteer.launch({
      args: chromium.args,
      executablePath: await chromium.executablePath(),
      headless: "shell",
    });
  } else {
    const { default: puppeteer } = await import("puppeteer");

    browser = await puppeteer.launch({
      headless: true,
    });
  }

  try {
    const page = await browser.newPage();
    await page.setContent(html, { waitUntil: "load" });

    return await page.pdf({
      format: "A4",
      printBackground: true,
      preferCSSPageSize: true,
    });
  } finally {
    await browser.close();
  }
}

module.exports = { generateAuditPDF };
